const camelToSnake = (key: string) => key.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const ageBucket = (n: number) => n <= 21 ? "18-21" : n <= 25 ? "22-25" : n <= 27 ? "25-27" : n <= 32 ? "28-32" : n <= 38 ? "33-38" : n <= 45 ? "39-45" : n <= 55 ? "46-55" : "55+";

/** The closest allowed option for a field: exact value, exact label, then a containment either way. Free-text fields pass through. */
export function closestOption(field: TraitField, raw: string): string | undefined {
  const value = raw.trim().toLowerCase();
  if (!value) return undefined;
  if (!field.options) return raw.trim().slice(0, 200);
  if (field.key === "age_range") { const n = /\d+/.exec(value); if (n && !field.options.some(o => o.value === value)) return ageBucket(Number(n[0])); }
  const slug = value.replace(/[\s/_]+/g, "-");
  const exact = field.options.find(o => o.value === slug || o.label.toLowerCase() === value);
  if (exact) return exact.value;
  // Otherwise the option whose tokens cover the most of the input: "dark chocolate brown" → dark-brown, not brown.
  const tokens = new Set(slug.split("-").filter(Boolean));
  const scored = field.options.map(o => { const parts = o.value.split("-"); const hits = parts.filter(t => tokens.has(t)).length; return { o, hits, fraction: hits / parts.length }; }).filter(s => s.hits > 0).sort((a, b) => b.hits - a.hits || b.fraction - a.fraction);
  if (scored.length) return scored[0].o.value;
  return field.options.find(o => o.label.toLowerCase().split(/[\s/()]+/).includes(value))?.value;
}
/** Normalise a loose trait object (camelCase or snake_case keys, any spelling) to allowed values. */
export function normalizeTraits(input: Record<string, unknown>): Traits {
  const out: Traits = {};
  for (const [rawKey, rawValue] of Object.entries(input)) {
    if (typeof rawValue !== "string") continue;
    const key = camelToSnake(rawKey);
    const field = TRAIT_FIELDS.find(f => f.key === key);
    if (!field) continue;
    const value = closestOption(field, rawValue);
    if (value) out[key] = value;
  }
  return out;
}
const label = (key: string, value: string) => TRAIT_FIELDS.find(f => f.key === key)?.options?.find(o => o.value === value)?.label.replace(/\s*\(.*\)$/, "").toLowerCase() ?? value.replaceAll("-", " ");
const agePhrase = (range: string | undefined, pronoun: string) => range ? ({ "18-21": "around 20", "22-25": `in ${pronoun} early 20s`, "25-27": `in ${pronoun} mid-20s`, "28-32": "around 30", "33-38": `in ${pronoun} mid-30s`, "39-45": `in ${pronoun} early 40s`, "46-55": "around 50", "55+": `in ${pronoun} late 50s or older` }[range] ?? range) : undefined;
const ethnicityWord = (value: string) => label("ethnicity", value).split(" / ")[0].replace(/^other$/, "").trim();
const article = (phrase: string) => /^[aeiou]/i.test(phrase) ? "An" : "A";

/** One locked-features sentence group from discrete traits: the base prompt an identity carries into every generation. */
export function traitsToPrompt(traits: Traits): string {
  const t = traits;
  const noun = t.gender === "female" ? "woman" : t.gender === "male" ? "man" : "person", pronoun = t.gender === "female" ? "her" : t.gender === "male" ? "his" : "their";
  const who = [t.ethnicity ? ethnicityWord(t.ethnicity) : undefined, noun, agePhrase(t.age_range, pronoun)].filter(Boolean).join(" ");
  const eyes = [t.eye_color && label("eye_color", t.eye_color), t.eye_shape && label("eye_shape", t.eye_shape)].filter(Boolean).join(" ");
  const face = [eyes && `${eyes} eyes`, t.face_shape && `${label("face_shape", t.face_shape)} face`, t.jawline && `${label("jawline", t.jawline)} jawline`, t.nose_type && `${label("nose_type", t.nose_type)} nose`, t.lip_type && `${label("lip_type", t.lip_type)} lips`, t.eyebrow_shape && `${label("eyebrow_shape", t.eyebrow_shape)} eyebrows`].filter(Boolean).join(", ");
  const skin = [t.skin_tone, t.skin_undertone && !/undertone/i.test(t.skin_tone ?? "") && `${label("skin_undertone", t.skin_undertone)} undertones`].filter(Boolean).join(" skin with ") || "";
  const hair = [t.hair_color && label("hair_color", t.hair_color), t.hair_length && label("hair_length", t.hair_length), t.hair_style && label("hair_style", t.hair_style)].filter(Boolean).join(", ");
  const hairLine = hair ? `${hair} hair${t.hair_texture ? ` with a ${label("hair_texture", t.hair_texture)} texture` : ""}${t.hair_highlight_color ? ` and ${t.hair_highlight_color} highlights` : ""}` : "";
  const body = [t.height_category && `${label("height_category", t.height_category)} height`, t.body_shape && `${label("body_shape", t.body_shape)} build`, t.muscle_definition && `${label("muscle_definition", t.muscle_definition)} muscle definition`, t.shoulder_width && `${label("shoulder_width", t.shoulder_width)} shoulders`, t.waist_definition && `${label("waist_definition", t.waist_definition)} waist`, t.hip_width && `${label("hip_width", t.hip_width)} hips`, t.bust_volume && `${label("bust_volume", t.bust_volume)} bust`].filter(Boolean).join(", ");
  const details = t.appearance_details?.trim();
  const sentences = [`${article(who)} ${who}${face ? ` with ${face}` : ""}.`, skin && `${skin.charAt(0).toUpperCase()}${skin.slice(1)}${skin.includes(" skin") ? "" : " skin"}, natural skin texture with visible pores.`, hairLine && `${hairLine.charAt(0).toUpperCase()}${hairLine.slice(1)}.`, body && `${body.charAt(0).toUpperCase()}${body.slice(1)}.`, details && `${details.charAt(0).toUpperCase()}${details.slice(1).replace(/\.?$/, ".")}`];
  return sentences.filter(Boolean).join(" ");
}

/** The parser prompt: every allowed value spelled out, so the model picks rather than invents. */
export function traitParserPrompt(description: string): string {
  const lines = TRAIT_FIELDS.map(f => `- ${f.key}: ${f.options ? f.options.map(o => `"${o.value}"`).join(" | ") : "free text"}`).join("\n");
  return `You are an expert at extracting structured appearance traits from a description of a person. The input may be natural language or a JSON image prompt.
Return ONLY a JSON object whose keys are the trait names below and whose values EXACTLY match the allowed options (or free text where noted). Omit traits that cannot be inferred. Always pick the CLOSEST allowed option, never invent values.
Inference rules: map ages to the range they fall in ("approx 23" → "22-25"); "dark chocolate brown" hair → "dark-brown"; "long textured waves" → hair_length "long", hair_style "wavy"; "olive skin" → skin_tone "olive", skin_undertone "olive"; "athletic build" → body_shape "athletic", muscle_definition "toned"; form-fitting clothing suggests waist_definition "defined". Put tattoos, piercings, makeup and other distinctive features in appearance_details. Also return "suggested_name": a first name that suits the person.

TRAITS:
${lines}

DESCRIPTION:
${description}`;
}
export async function parseTraits(description: string, ask: (prompt: string) => Promise<string>): Promise<{ traits: Traits; suggestedName?: string }> {
  const raw = (await ask(traitParserPrompt(description))).trim().replace(/^```(?:json)?\s*/i, "").replace(/\s*```$/, "");
  let parsed: Record<string, unknown> = {};
  try { parsed = JSON.parse(raw); } catch { const m = /\{[\s\S]*\}/.exec(raw); if (m) { try { parsed = JSON.parse(m[0]); } catch { parsed = {}; } } }
  if (parsed && typeof parsed === "object" && parsed.prompt && typeof parsed.prompt === "object") parsed = parsed.prompt as Record<string, unknown>;
  const name = parsed.suggested_name ?? parsed.suggestedName;
  return { traits: normalizeTraits(parsed), suggestedName: typeof name === "string" ? name.trim().slice(0, 60) || undefined : undefined };
}
